"""Small 2-D density-scaling FWI check inspired by Singh et al. (2025).

This is an independent numerical smoke test, not a reproduction of their code or
paper results. It uses the same form of scalar PDE, a much coarser grid, and a
synthetic observation generated by the same discretization.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import torch


def configuration(device: torch.device, refinement: int = 1) -> dict:
    nx, ny, steps = 64 * refinement, 32 * refinement, 420
    lx, ly, dt = 0.1, 0.05, 4e-8
    dx, dy = lx / nx, ly / ny
    c, rho, frequency = 6000.0, 2700.0, 500_000.0
    assert c * dt * math.sqrt(dx**-2 + dy**-2) < 1.0
    sources = torch.tensor([[22, 1], [42, 1]], device=device) * refinement
    receiver_x = torch.arange(7, 58, 3, device=device) * refinement
    receiver_y = torch.ones_like(receiver_x) * refinement
    basis = torch.zeros((2, nx, ny), dtype=torch.float64, device=device)
    basis[torch.arange(2, device=device), sources[:, 0], sources[:, 1]] = 1.0
    times = torch.arange(steps, dtype=torch.float64, device=device) * dt
    omega = 2 * math.pi * frequency
    pulse = torch.where(
        times <= 2 / frequency,
        torch.sin(omega * times) * torch.sin(omega * times / 4) ** 2,
        torch.zeros_like(times),
    )
    return dict(
        nx=nx, ny=ny, lx=lx, ly=ly, dt=dt, dx=dx, dy=dy, steps=steps,
        c=c, rho=rho, frequency=frequency, sources=sources,
        receiver_x=receiver_x, receiver_y=receiver_y, basis=basis,
        pulse=pulse, force_amplitude=1e9, device=device,
    )


def forward(gamma: torch.Tensor, cfg: dict) -> torch.Tensor:
    """Return displacement traces with shape (source, receiver, time)."""
    nx, ny = cfg["nx"], cfg["ny"]
    assert gamma.shape == (nx, ny)
    if bool((gamma <= 0).any()):
        raise ValueError("Density scale gamma must be positive")
    u_prev = torch.zeros((2, nx, ny), dtype=gamma.dtype, device=gamma.device)
    u_curr = torch.zeros_like(u_prev)
    gx = 0.5 * (gamma[1:, :] + gamma[:-1, :]) / cfg["dx"] ** 2
    gy = 0.5 * (gamma[:, 1:] + gamma[:, :-1]) / cfg["dy"] ** 2
    dt2 = cfg["dt"] ** 2
    drive = dt2 * cfg["force_amplitude"] / (cfg["rho"] * cfg["dx"] * cfg["dy"])
    traces = []
    for sample in cfg["pulse"]:
        flux_x = gx * (u_curr[:, 1:, :] - u_curr[:, :-1, :])
        flux_y = gy * (u_curr[:, :, 1:] - u_curr[:, :, :-1])
        div_x = torch.nn.functional.pad(flux_x, (0, 0, 0, 1)) - torch.nn.functional.pad(flux_x, (0, 0, 1, 0))
        div_y = torch.nn.functional.pad(flux_y, (0, 1)) - torch.nn.functional.pad(flux_y, (1, 0))
        force = drive * sample * cfg["basis"]
        u_next = 2 * u_curr - u_prev + (dt2 * cfg["c"] ** 2 * (div_x + div_y) + force) / gamma
        if "receiver_weights" in cfg:
            traces.append(u_next.flatten(1) @ cfg["receiver_weights"].flatten(1).T)
        else:
            traces.append(u_next[:, cfg["receiver_x"], cfg["receiver_y"]])
        u_prev, u_curr = u_curr, u_next
    return torch.stack(traces, dim=-1)


def defect_model(cfg: dict) -> torch.Tensor:
    x = (torch.arange(cfg["nx"], device=cfg["device"], dtype=torch.float64) + 0.5) * cfg["dx"]
    y = (torch.arange(cfg["ny"], device=cfg["device"], dtype=torch.float64) + 0.5) * cfg["dy"]
    radius = (x[:, None] - 0.05) ** 2 / 0.007**2 + (y[None, :] - 0.025) ** 2 / 0.005**2
    return torch.where(radius < 1.0, 0.35, 1.0)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--iterations", type=int, default=12)
    parser.add_argument("--reference-refinement", type=int, choices=(1, 2), default=1)
    parser.add_argument("--calibrate-homogeneous-gain", action="store_true")
    parser.add_argument("--cpu", action="store_true")
    args = parser.parse_args()
    if args.iterations < 1:
        raise ValueError("iterations must be positive")
    torch.manual_seed(7)
    device = torch.device("cpu" if args.cpu or not torch.cuda.is_available() else "cuda")
    cfg = configuration(device)
    if args.calibrate_homogeneous_gain and args.reference_refinement == 1:
        raise ValueError("Gain calibration requires a separate reference grid")
    true_gamma = defect_model(cfg)
    reference_cfg = configuration(device, refinement=args.reference_refinement)
    reference_gamma = defect_model(reference_cfg)
    with torch.no_grad():
        observed = forward(reference_gamma, reference_cfg)
        repeat_error = (forward(reference_gamma, reference_cfg) - observed).abs().max().item()
        discretization_mismatch = (forward(true_gamma, cfg) - observed).square().mean().sqrt().item()
        if args.calibrate_homogeneous_gain:
            fine_background = forward(torch.ones_like(reference_gamma), reference_cfg)
            coarse_background = forward(torch.ones_like(true_gamma), cfg)
            gain = (fine_background * coarse_background).sum() / coarse_background.square().sum()
            background_rmse_before = (fine_background - coarse_background).square().mean().sqrt().item()
            background_rmse_after = (fine_background - gain * coarse_background).square().mean().sqrt().item()
        else:
            gain = torch.ones((), dtype=true_gamma.dtype, device=device)
            background_rmse_before = None
            background_rmse_after = None
    assert torch.isfinite(observed).all()
    assert observed.abs().max().item() > 0
    scale = observed.abs().max().detach()

    # Independent central-difference directional derivative of the same discrete model.
    start = torch.full_like(true_gamma, 0.8, requires_grad=True)
    direction = torch.zeros_like(start)
    direction[14:50, 6:27] = torch.randn((36, 21), dtype=start.dtype, device=device)
    direction /= direction.norm()

    def loss(model: torch.Tensor) -> torch.Tensor:
        return 0.5 * torch.mean(((gain * forward(model, cfg) - observed) / scale) ** 2)

    initial_grad_loss = loss(start)
    grad = torch.autograd.grad(initial_grad_loss, start)[0]
    projected = (grad * direction).sum().item()
    finite_difference = {}
    for epsilon in (0.02, 0.01):
        with torch.no_grad():
            fd = (loss(start + epsilon * direction) - loss(start - epsilon * direction)) / (2 * epsilon)
        finite_difference[str(epsilon)] = fd.item()
    errors = {e: abs(v - projected) / max(abs(projected), 1e-12) for e, v in finite_difference.items()}

    # This is a numerical optimizer smoke check, not an image-quality assessment.
    model = torch.nn.Parameter(torch.ones_like(true_gamma))
    optimizer = torch.optim.Adam([model], lr=0.04)
    history = []
    for _ in range(args.iterations):
        optimizer.zero_grad(set_to_none=True)
        current = loss(model)
        history.append(current.item())
        current.backward()
        model.grad[:, :4] = 0
        model.grad[:4, :] = 0
        model.grad[-4:, :] = 0
        optimizer.step()
        with torch.no_grad():
            model.clamp_(0.3, 1.0)
    with torch.no_grad():
        final_loss = loss(model).item()
    history.append(final_loss)
    assert all(math.isfinite(v) for v in history)
    assert final_loss < history[0], history
    assert errors["0.01"] < 0.02, errors

    report = dict(
        status="numerical_smoke_only", device=str(device), dtype="float64",
        grid=[cfg["nx"], cfg["ny"]], sources=2,
        reference_grid=[reference_cfg["nx"], reference_cfg["ny"]],
        reference_refinement=args.reference_refinement,
        receivers=int(cfg["receiver_x"].numel()), steps=cfg["steps"],
        repeat_forward_max_abs_error=repeat_error,
        true_material_cross_grid_trace_rmse=discretization_mismatch,
        calibrated_source_gain=float(gain.item()),
        homogeneous_trace_rmse_before_gain=background_rmse_before,
        homogeneous_trace_rmse_after_gain=background_rmse_after,
        directional_autograd=projected,
        directional_central_difference=finite_difference,
        relative_directional_errors=errors,
        loss_history=history,
        initial_loss=history[0], final_loss=final_loss,
        material_min=float(model.detach().min().item()),
        material_max=float(model.detach().max().item()),
        mean_reconstructed_inside_defect=float(model.detach()[true_gamma < 0.5].mean().item()),
        mean_reconstructed_outside_defect=float(model.detach()[true_gamma >= 0.5].mean().item()),
        reference_note=(
            "Observed and inverse data use the same discretization."
            if args.reference_refinement == 1 else
            "Observed data use a 2x grid, but the same discrete scheme and idealized physics."
        ),
    )
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    torch.save(dict(traces=observed.cpu(), true_gamma=true_gamma.cpu(), reconstructed_gamma=model.detach().cpu()), args.out / "fields.pt")
    import matplotlib.pyplot as plt

    with torch.no_grad():
        predicted = (gain * forward(model, cfg)).cpu()
    fig, axes = plt.subplots(2, 2, figsize=(9, 6), constrained_layout=True)
    extent = (0, cfg["lx"] * 1e3, 0, cfg["ly"] * 1e3)
    for ax, field, title in zip(
        axes[0], (true_gamma, model.detach()), ("True density scale", "Reconstructed density scale")
    ):
        im = ax.imshow(field.cpu().T, origin="lower", extent=extent, vmin=0.3, vmax=1.0)
        ax.set(title=title, xlabel="x (mm)", ylabel="y (mm)")
        fig.colorbar(im, ax=ax, shrink=0.8)
    t_us = torch.arange(cfg["steps"]) * cfg["dt"] * 1e6
    axes[1, 0].plot(t_us, observed[0, 8].cpu(), label="Observed")
    axes[1, 0].plot(t_us, predicted[0, 8], label="Predicted", alpha=0.8)
    axes[1, 0].set(title="One receiver trace", xlabel="Time (us)", ylabel="Displacement")
    axes[1, 0].legend()
    axes[1, 1].semilogy(history)
    axes[1, 1].set(title="Waveform loss", xlabel="Iteration", ylabel="Normalized MSE / 2")
    fig.savefig(args.out / "smoke_check.png", dpi=150)
    plt.close(fig)
    print(json.dumps({k: report[k] for k in ("device", "initial_loss", "final_loss", "relative_directional_errors")}, indent=2))


if __name__ == "__main__":
    main()
